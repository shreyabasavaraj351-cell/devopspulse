from collections import Counter
from datetime import datetime, timedelta, timezone

from fastapi import APIRouter, Depends
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.core.deps import get_org_user
from app.database.session import get_db
from app.models.models import AnalysisHistory, Deployment, Incident, User
from app.services.analysis_pipeline import deployment_out, incident_out

router = APIRouter(prefix="/dashboard", tags=["dashboard"])


@router.get("/summary")
def summary(project_id: int | None = None, user: User = Depends(get_org_user), db: Session = Depends(get_db)):
    org = user.organization_id

    def scoped(model, stmt):
        stmt = stmt.where(model.organization_id == org)
        return stmt.where(model.project_id == project_id) if project_id else stmt

    total = db.scalar(scoped(Deployment, select(func.count(Deployment.id)))) or 0
    failed = db.scalar(scoped(Deployment, select(func.count(Deployment.id)).where(Deployment.status == "failed"))) or 0
    open_inc = db.scalar(scoped(Incident, select(func.count(Incident.id)).where(Incident.status != "resolved"))) or 0
    since = datetime.now(timezone.utc) - timedelta(days=30)
    risk_alerts = db.scalar(
        scoped(
            AnalysisHistory,
            select(func.count(AnalysisHistory.id)).where(
                AnalysisHistory.kind == "risk",
                AnalysisHistory.risk_level.in_(["high", "medium"]),
                AnalysisHistory.created_at >= since,
            ),
        )
    ) or 0

    recent_deps = db.scalars(scoped(Deployment, select(Deployment)).order_by(Deployment.id.desc()).limit(8)).all()
    recent_inc = db.scalars(scoped(Incident, select(Incident)).order_by(Incident.id.desc()).limit(5)).all()
    all_inc = db.scalars(scoped(Incident, select(Incident))).all()

    # Insights are computed from stored records (not generated by the LLM), so they are always grounded.
    insights = []
    if all_inc:
        top_cat, n = Counter(i.category for i in all_inc).most_common(1)[0]
        insights.append(f"Most common failure category: {top_cat} ({n} of {len(all_inc)} incidents).")
        influenced = sum(1 for i in all_inc if i.memory_influenced)
        if influenced:
            insights.append(f"Memory shaped the recommendation on {influenced} incident(s).")
        unverified = sum(1 for i in all_inc if i.status == "open")
        if unverified:
            insights.append(f"{unverified} incident(s) have no confirmed outcome yet. Submitting feedback lets the agent learn from them.")
        crit = sum(1 for i in all_inc if i.severity in ("critical", "high") and i.status != "resolved")
        if crit:
            insights.append(f"{crit} high or critical incident(s) are still open.")
    else:
        insights.append("No incidents yet. Analyse a deployment log to get started.")

    return {
        "total_deployments": total,
        "successful_deployments": total - failed,
        "failed_deployments": failed,
        "open_incidents": open_inc,
        "risk_alerts": risk_alerts,
        "recent_deployments": [deployment_out(d) for d in recent_deps],
        "recent_incidents": [incident_out(i) for i in recent_inc],
        "insights": insights,
    }
